T2S = {}
S2T = {}
for _p in _PAIRS:
    if len(_p) == 2 and _p[0] != _p[1]:
        _t, _s = _p[0], _p[1]
        T2S[_t] = _s
        S2T.setdefault(_s, set()).add(_t)


def variants(ch):
    """一个字的全部繁简写法(含自身)。"""
    s = T2S.get(ch, ch)
    return {ch, s} | S2T.get(s, set())


def pattern(token):
    """把一个搜索词改写成繁简不敏感的正则源码。其它字符原样(已转义)。"""
    out = []
    for ch in token:
        vs = variants(ch)
        if len(vs) == 1:
            out.append(re.escape(ch))
        else:
            out.append("[" + "".join(re.escape(v) for v in sorted(vs)) + "]")
    return "".join(out)
